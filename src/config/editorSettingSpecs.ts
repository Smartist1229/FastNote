interface SpecBase {
  /** EditorSettings 的字段名，同时是数据库键 app.config.editor.<field> */
  field: keyof EditorSettings;
  group: EditorSettingGroup;
  title: string;
  desc: string;
  /** 供设置搜索命中的额外关键词 */
  keywords?: string;
  /** 依赖的开关没打开时置灰（控件保留在原位，提示用户为什么不能改） */
  disabledWhen?: (s: EditorSettings) => boolean;
}

/** 三种控件：开关 / 数字 / 分段（枚举） */
export type EditorSettingSpec =
  | (SpecBase & { kind: "toggle" })
  | (SpecBase & {
      kind: "number";
      min: number;
      max: number;
      /** 默认 1；小于 1 时输入框保留对应小数位 */
      step?: number;
      /** 数值单位后缀（px、ms、em…） */
      unit?: string;
    })
  | (SpecBase & { kind: "segment"; options: { value: string; label: string }[] });

