export const LABELS: Record<MarkdownEditorLocale, Record<string, string>> = {
  "en-US": EN_LABELS,
  "zh-CN": ZH_LABELS,
};

export const resolveLocaleLabels = (
  locale: MarkdownEditorLocale = "en-US",
  overrides: Record<string, string | undefined> = {},
): Record<string, string> => {
  const labels = { ...LABELS["en-US"], ...LABELS[locale] };
  for (const [key, value] of Object.entries(overrides)) {
    if (value !== undefined) labels[key] = value;
  }
  return labels;
};
